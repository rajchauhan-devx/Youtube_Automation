import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(new URL('../../server/package.json',import.meta.url));
const express=require('express'),{chromium}=require('playwright');
const directory=fs.mkdtempSync(path.join(os.tmpdir(),'motion-library-browser-'));
process.env.TUBEFLOW_DATA_DIR=directory;
fs.writeFileSync(path.join(directory,'accounts.json'),JSON.stringify([{id:'default',name:'Ancient Dharma',color:'#C59B52',avatar:'AD'}]));
const {workspacesRouter}=await import('../../server/dist/routes/workspaces.js');
const {accountsRouter}=await import('../../server/dist/routes/accounts.js');
const app=express();app.use(express.json());
app.use('/api/accounts/:accountId/profiles/:profile',workspacesRouter);app.use('/api/accounts',accountsRouter);app.use(express.static(path.resolve('dist')));
const server=await new Promise(resolve=>{const s=app.listen(0,'127.0.0.1',()=>resolve(s));});
const browser=await chromium.launch({headless:true});
try{
  const page=await browser.newPage({viewport:{width:1440,height:1100}}),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(`http://127.0.0.1:${server.address().port}`,{waitUntil:'networkidle'});
  await page.getByRole('button',{name:'Motion Templates',exact:true}).first().click();
  await page.getByText('20 adaptive families · landscape and portrait',{exact:true}).waitFor();
  await page.getByRole('button',{name:/Timeline & eras/}).click();
  const labels=['पहला चरण','दूसरा चरण','तीसरा चरण','चौथा चरण','पाँचवाँ चरण','छठा चरण','सातवाँ चरण'];
  await page.getByLabel('Demo labels',{exact:true}).fill(labels.join('\n'));
  await page.getByLabel('Pause preview',{exact:true}).click();
  await page.getByLabel('Preview time',{exact:true}).fill('45');
  assert.deepEqual(await page.getByRole('alert').allTextContents(),[]);
  await page.waitForFunction(()=>document.querySelectorAll('[aria-label="Motion template preview"] text').length===7,undefined,{timeout:10000});
  assert.equal(await page.locator('[aria-label="Motion template preview"] text').count(),7);
  assert.equal(await page.getByRole('alert').count(),0);
  await page.getByLabel('Preview duration',{exact:true}).selectOption('8');
  await page.getByLabel('Preview time',{exact:true}).fill('60');
  const output=path.resolve('artifacts/motion-library-proof');fs.mkdirSync(output,{recursive:true});
  await page.screenshot({path:path.join(output,'landscape.png'),fullPage:true});
  await page.getByLabel('Preview aspect ratio',{exact:true}).selectOption('9:16');
  await page.getByLabel('Preview time',{exact:true}).fill('60');
  assert.equal(await page.locator('[aria-label="Motion template preview"] svg').getAttribute('viewBox'),'0 0 1080 1920');
  assert.equal(await page.locator('[aria-label="Motion template preview"] text').count(),7);
  await page.screenshot({path:path.join(output,'portrait.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:path.join(output,'mobile.png'),fullPage:true});
  await page.getByLabel('Demo labels',{exact:true}).fill('पहला चरण');
  await page.getByRole('alert').filter({hasText:/requires 2/}).waitFor();
  assert.deepEqual(errors,[]);
  console.log('MOTION_LIBRARY_BROWSER_PASSED: seven editable Hindi timeline events, duration, portrait reflow, mobile bounds and invalid-content feedback');
}finally{await browser.close();await new Promise(resolve=>server.close(resolve));fs.rmSync(directory,{recursive:true,force:true});}
