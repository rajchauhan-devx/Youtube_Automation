import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {SceneGraph,identity} from '@tubeflow/editing-contracts';
const require=createRequire(new URL('../../server/package.json',import.meta.url));
const express=require('express'),{chromium}=require('playwright');
const directory=fs.mkdtempSync(path.join(os.tmpdir(),'graph-studio-browser-'));
process.env.TUBEFLOW_DATA_DIR=directory;process.env.AI_EDITING_ENABLED='true';
const {fixture}=await import('./motion-fixtures.mjs');
const {nextRevision,publish}=await import('../../server/dist/services/editing/repository.js');
const {store}=await import('../../server/dist/services/store.js');
const {workspacesRouter}=await import('../../server/dist/routes/workspaces.js');
const {accountsRouter}=await import('../../server/dist/routes/accounts.js');
const original=await fixture('museum',false,true),p=nextRevision(original),scene=p.scenes[0];
p.settings.graphicEngine='generative';p.settings.visualReview=false;
p.artifacts=[{id:'original',sceneId:scene.id,enabled:true,intent:'Bronze statue',narrativeRefs:scene.narrativeRefs,startFrame:0,endFrame:72,priority:5,nodes:[],assetRequestIds:[],sceneGraph:SceneGraph.parse({version:1,seed:42,bounds:{x:40,y:70,width:560,height:220},nodes:[{id:'subject',kind:'text',space:'screen',zIndex:0,transform:identity(),opacity:1,tracks:[],text:'bronze statue',bounds:{x:20,y:20,width:220,height:60},style:{fontAssetId:p.style.fontAssetIds[0],fontSize:24,fontWeight:'700',color:'#FFFFFF',align:'left',lineHeight:1.3}}],soundCues:[],evidence:[{targetNodeId:'subject',sourceId:scene.id,narrationTokenIds:scene.narrativeRefs,verifiedValue:'bronze statue',status:'narration'}],capabilities:['svg-2d']})}];
publish(p,original.revisionId);
store.add('scripts',{id:p.scriptId,name:'Original motion graphics browser proof',accountId:'default',section:'shorts',status:'active',locked:false,prompts:[],pipeline:[],howItWorks:'',duration:3,lastUsed:new Date().toISOString(),editingProjectId:p.id,generatedAudio:[],generatedImages:[]});
const app=express();app.use(express.json());app.use('/api/accounts/:accountId/profiles/:profile',workspacesRouter);app.use('/api/accounts',accountsRouter);app.use(express.static(path.resolve('dist')));
const server=await new Promise(resolve=>{const s=app.listen(0,'127.0.0.1',()=>resolve(s));});
const browser=await chromium.launch({headless:true});
try {
  const page=await browser.newPage({viewport:{width:1440,height:1100}}),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.addInitScript(id=>localStorage.setItem('tubeflow:v1',JSON.stringify({channelId:'default',section:'shorts',tab:'artifacts',selectedScriptId:id})),p.scriptId);
  await page.goto(`http://127.0.0.1:${server.address().port}`,{waitUntil:'networkidle'});
  await page.getByLabel('Composition text subject').waitFor();
  await page.getByRole('button',{name:'Watch demos',exact:true}).click();
  const comparison = page.getByLabel('Comparison demo video',{exact:true});
  await comparison.waitFor();
  await comparison.evaluate(video => video.play());
  await page.waitForFunction(() => document.querySelector('video[aria-label="Comparison demo video"]').currentTime > 0.2);
  assert.equal(await comparison.evaluate(video => video.muted),false);
  assert.equal(await comparison.evaluate(video => Math.round(video.duration)),8);
  await page.getByRole('button',{name:'Branching diagram',exact:true}).click();
  const branching = page.getByLabel('Branching diagram demo video',{exact:true});
  await branching.waitFor();
  await branching.evaluate(video => video.play());
  await page.waitForFunction(() => document.querySelector('video[aria-label="Branching diagram demo video"]').currentTime > 0.2);
  const range = await page.request.get(`http://127.0.0.1:${server.address().port}/motion-demos/branching.mp4`,{headers:{Range:'bytes=0-127'}});
  assert.equal(range.status(),206);assert.equal((await range.body()).length,128);
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.getByRole('button',{name:'Close demos',exact:true}).click();
  assert.equal(await page.locator('video[aria-label$="demo video"]').count(),0);
  await page.setViewportSize({width:1440,height:1100});
  await page.getByLabel('Sound design',{exact:true}).selectOption('balanced');
  await page.getByRole('button',{name:'Apply motion & sound to this project',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[aria-label="Sound design"]').value==='balanced'&&!Array.from(document.querySelectorAll('button')).some(b=>b.textContent==='Apply motion & sound to this project'));
  await page.getByLabel('Play video',{exact:true}).click();
  await page.waitForFunction(()=>Number(document.querySelector('[aria-label="Timeline playhead"]').value)>10);
  await page.getByLabel('Pause video',{exact:true}).click();
  assert.ok(await page.locator('[data-node-id="subject"]').count());
  await page.getByLabel('Composition text subject').fill('statue');
  const savedResponse = page.waitForResponse(response => response.request().method() === 'PATCH' && response.url().includes('/artifacts/original'));
  await page.getByRole('button',{name:'Save changes',exact:true}).click();
  const saved = await savedResponse;assert.equal(saved.status(),200);
  assert.equal((await saved.json()).project.artifacts[0].sceneGraph.nodes[0].text,'statue');
  await page.waitForFunction(() => !document.body.textContent.includes('Unsaved graphic changes'));
  await page.waitForFunction(()=>document.querySelector('[aria-label="Composition text subject"]').value==='statue'&&Array.from(document.querySelectorAll('button')).find(b=>b.textContent==='Save changes')?.disabled);
  const output=path.resolve('artifacts/scene-graph-proof');fs.mkdirSync(output,{recursive:true});
  await page.screenshot({path:path.join(output,'studio.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  assert.deepEqual(errors,[]);
  console.log('SCENE_GRAPH_BROWSER_PASSED: both in-app demos play with sound, range requests, demo close/stop, composition rendering, saved edits and mobile layout');
} finally {await browser.close();await new Promise(resolve=>server.close(resolve));fs.rmSync(directory,{recursive:true,force:true});}
