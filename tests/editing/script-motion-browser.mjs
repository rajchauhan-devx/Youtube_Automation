import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(new URL('../../server/package.json',import.meta.url));
const express=require('express'),{chromium}=require('playwright');
const directory=fs.mkdtempSync(path.join(os.tmpdir(),'script-motion-browser-'));
process.env.TUBEFLOW_DATA_DIR=directory;
process.env.AI_EDITING_ENABLED='true';
fs.writeFileSync(path.join(directory,'accounts.json'),JSON.stringify([{id:'default',name:'Ancient Dharma',color:'#C59B52',avatar:'AD'}]));
const {fixture}=await import('./motion-fixtures.mjs');
const {generateSceneGraph}=await import('../../server/dist/services/editing/sceneGraphGeneration.js');
const {serializeScenePlan}=await import('../../server/dist/services/scene-plan-format.js');
const {store}=await import('../../server/dist/services/store.js');
const {scriptFingerprint}=await import('../../server/dist/services/editing/projects.js');
const {nextRevision,publish}=await import('../../server/dist/services/editing/repository.js');
const {workspacesRouter}=await import('../../server/dist/routes/workspaces.js');
const {accountsRouter}=await import('../../server/dist/routes/accounts.js');
const original=await fixture('science',false,true),project=nextRevision(original);
project.inputs.width=1920;project.inputs.height=1080;
const hint={version:1,templateId:'ad_lower_third',intent:'Introduce the narrated concept',quote:'पानी गर्म होता है',position:'bottom',durationSec:2,content:{items:[{text:'पानी गर्म होता है'}],links:[]}};
const plan={version:1,title:'Motion plan proof',thumbnailPrompt:'A stone temple',scenes:[{id:'scene_001',chapter:'Knowledge',role:'story',narration:project.inputs.narrationText,imagePrompt:'A stone temple',mediaType:'image',motionGraphics:[hint]}]};
project.artifacts=[await generateSceneGraph(project,project.scenes[0],{...hint,sceneId:project.scenes[0].id},{signal:AbortSignal.timeout(30000),job:{usage:[]},maxCalls:8,persist:()=>{},stage:()=>{}},'fixture',undefined,{openArea:'center'})];
project.sceneOutcomes=[{sceneId:project.scenes[0].id,state:'complete',reason:hint.intent,artifactIds:project.artifacts.map(a=>a.id)}];
const savedScript={...store.getById('scripts',project.scriptId),id:project.scriptId,name:'Script motion integration proof',accountId:'default',section:'shorts',status:'active',locked:false,prompts:[],howItWorks:'',duration:3,lastUsed:'Never',editingProjectId:project.id,scenePlan:plan,aiResponse:serializeScenePlan(plan),pipeline:[{id:'response',label:'Response',status:'done',summary:'Complete',inputLog:'',outputPreview:''}]};
project.inputs.scriptHash=scriptFingerprint(savedScript);
store.add('scripts',savedScript);
publish(project,original.revisionId);
const app=express();app.use(express.json());app.use('/api/accounts/:accountId/profiles/:profile',workspacesRouter);app.use('/api/accounts',accountsRouter);app.use(express.static(path.resolve('dist')));
const server=await new Promise(resolve=>{const instance=app.listen(0,'127.0.0.1',()=>resolve(instance));});
const executablePath=[process.env.EDITING_BROWSER_EXECUTABLE,'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'].find(file=>file&&fs.existsSync(file));
const browser=await chromium.launch({headless:true,...(executablePath?{executablePath}:{})});
try{
  const page=await browser.newPage({viewport:{width:1440,height:1100}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(scriptId=>localStorage.setItem('tubeflow:v1',JSON.stringify({channelId:'default',section:'shorts',tab:'preview',selectedScriptId:scriptId})),project.scriptId);
  await page.goto(`http://127.0.0.1:${server.address().port}`,{waitUntil:'networkidle'});
  const panel=page.getByLabel('Script motion plans',{exact:true});await panel.waitFor();
  await panel.locator('summary').click();
  await panel.getByText('Scene 1 · Speaker lower third',{exact:true}).waitFor();
  assert.ok((await panel.innerText()).includes('Position: bottom · 2s'));
  const output=path.resolve('artifacts/script-motion-proof');fs.mkdirSync(output,{recursive:true});
  await panel.screenshot({path:path.join(output,'preview-plan.png')});
  await page.getByRole('button',{name:'Artifacts',exact:false}).first().click();
  await page.getByLabel('Composition text item-0',{exact:true}).waitFor();
  assert.equal(await page.getByText('Media or narration changed. Generate a new revision to use the latest inputs.',{exact:true}).count(),0);
  assert.equal(await page.getByLabel('Composition text item-0',{exact:true}).inputValue(),'पानी गर्म होता है');
  await page.getByRole('button',{name:/Speaker lower third.*Introduce the narrated concept/}).click();
  await page.screenshot({path:path.join(output,'placed-artifact.png'),fullPage:true});
  await page.getByText('Choose narration & let AI plan motion graphics',{exact:true}).click();
  assert.equal(await page.getByLabel('Composition style',{exact:true}).inputValue(),'generative');
  assert.equal(await page.getByLabel('Composition style',{exact:true}).isDisabled(),true);
  assert.deepEqual(errors,[]);
  console.log('SCRIPT_MOTION_BROWSER_PASSED: Preview metadata panel, named native artifact, display content, and automatic adaptive engine selection');
}finally{await browser.close();await new Promise(resolve=>server.close(resolve));fs.rmSync(directory,{recursive:true,force:true});}
